export type PublicApiErrorCode = (typeof PUBLIC_API_ERROR_CODES)[number];

/** Keep `error` as the legacy string while adding a stable machine-readable code. */
export function publicError(
  context: Context,
  status: 400 | 401 | 403 | 404 | 409 | 429 | 500 | 502 | 503,
  code: PublicApiErrorCode,
  message: string,
  fields?: Record<string, "required" | "invalid_type" | "unsupported" | "too_many" | "out_of_range">
) {
  context.header("Cache-Control", "private, no-store");
  const requestId = context.res.headers.get("X-Request-Id") ?? undefined;
  return context.json({ error: message, code, ...(requestId ? { requestId } : {}), ...(fields ? { fields } : {}) }, status);
}
